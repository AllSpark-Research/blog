// ── Language Switcher Logic ──
(function() {
  'use strict';

  var STORAGE_KEY = 'allspark-lang';

  function getLang() {
    return localStorage.getItem(STORAGE_KEY) || 'en';
  }

  function setLang(lang) {
    localStorage.setItem(STORAGE_KEY, lang);
  }

  function applyLang(lang) {
    var dict = window.I18N[lang];
    if (!dict) return;

    // Update text content of all [data-i18n] elements
    var els = document.querySelectorAll('[data-i18n]');
    for (var i = 0; i < els.length; i++) {
      var key = els[i].getAttribute('data-i18n');
      if (dict[key] !== undefined) {
        // Use innerHTML for keys that contain HTML tags (like <strong>, <em>, <br>)
        var val = dict[key];
        if (val.indexOf('<') !== -1) {
          els[i].innerHTML = val;
        } else {
          els[i].textContent = val;
        }
      }
    }

    // Update attributes with data-i18n-attr
    var attrEls = document.querySelectorAll('[data-i18n-attr]');
    for (var j = 0; j < attrEls.length; j++) {
      var el = attrEls[j];
      var attrMap = el.getAttribute('data-i18n-attr');
      // Format: "title:key1,placeholder:key2"
      var pairs = attrMap.split(',');
      for (var k = 0; k < pairs.length; k++) {
        var parts = pairs[k].split(':');
        if (parts.length === 2) {
          var attrName = parts[0].trim();
          var attrKey = parts[1].trim();
          if (dict[attrKey] !== undefined) {
            el.setAttribute(attrName, dict[attrKey]);
          }
        }
      }
    }

    // Update <html lang="...">
    document.documentElement.setAttribute('lang', lang);

    // Update language switcher visual state
    var enSpan = document.querySelector('.nav-lang .en');
    var zhSpan = document.querySelector('.nav-lang .zh');
    if (enSpan && zhSpan) {
      if (lang === 'en') {
        enSpan.classList.add('active');
        zhSpan.classList.remove('active');
      } else {
        enSpan.classList.remove('active');
        zhSpan.classList.add('active');
      }
    }
  }

  function init() {
    var lang = getLang();
    applyLang(lang);

    // Expose applyLang globally for debugging/external access
    window.applyLang = applyLang;

    // Bind click on language toggle
    var langToggle = document.getElementById('lang-toggle');
    if (langToggle) {
      langToggle.addEventListener('click', function(e) {
        e.preventDefault();
        var current = getLang();
        var next = current === 'en' ? 'zh' : 'en';
        setLang(next);
        applyLang(next);
      });
    }
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', init);
  } else {
    init();
  }
})();
